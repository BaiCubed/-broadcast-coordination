#!/usr/bin/env python3
"""Migrate E20-E24 result figures and create data-driven NC-style replots.

The source figure tree is preserved for traceability.  Every CSV containing at
least one numeric column receives a PNG replot under ``data_replots``; each
numeric variable is shown with a half violin, point cloud, and embedded box.
"""
from __future__ import annotations

import csv
import shutil
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from PIL import Image

from ncstyle import configure, C1, C2, C3, C4, C5, C6, INK, GRID, SEQ, FS_TITLE, FS_LABEL, FS_TICK, LW_AXIS

configure()
plt.rcParams["font.sans-serif"] = ["Arial", "Liberation Sans", "Droid Sans Fallback", "SimSun", "DejaVu Sans"]
ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUTPUT = ROOT / "outputs"
DEST = ROOT / "outputs" / "results-E20-E24"
EXPERIMENTS = ["E20", "E21", "E22", "E23", "E24"]
PALETTE = [C1, C2, C3, C4, C5, C6]
SKIP_COLUMNS = {"seed", "seed_index", "pair_index", "N", "pressure_index", "conditions", "test_replications", "train_replications"}


def _style(ax):
    ax.spines["top"].set_visible(False); ax.spines["right"].set_visible(False)
    ax.spines["left"].set_linewidth(LW_AXIS); ax.spines["bottom"].set_linewidth(LW_AXIS)
    ax.grid(axis="y", color=GRID, linewidth=0.4); ax.set_axisbelow(True)


def _half_violin(ax, values, x, colour, seed):
    values = np.asarray(values, dtype=float); values = values[np.isfinite(values)]
    if not len(values): return
    vp = ax.violinplot(values, positions=[x], widths=.72, showextrema=False)
    body = vp["bodies"][0]; body.set_facecolor(colour); body.set_edgecolor(colour); body.set_alpha(.48)
    v = body.get_paths()[0].vertices; v[v[:, 0] > x, 0] = x
    rng = np.random.default_rng(seed); take = values if len(values) <= 800 else values[rng.choice(len(values), 800, replace=False)]
    ax.scatter(x + rng.uniform(.04, .34, len(take)), take, s=7, c=colour, alpha=.42, edgecolors="white", linewidths=.2, zorder=5)
    ax.boxplot([values], positions=[x - .06], widths=.18, patch_artist=True, showfliers=False,
               boxprops={"facecolor":"white","edgecolor":INK,"linewidth":.75},
               whiskerprops={"color":INK,"linewidth":.75}, capprops={"color":INK,"linewidth":.75},
               medianprops={"color":INK,"linewidth":1.8}, zorder=6)


def _replot_csv(csv_path: Path, out_path: Path) -> dict | None:
    try:
        frame = pd.read_csv(csv_path, low_memory=False)
    except Exception:
        return None
    numeric = []
    for col in frame.columns:
        vals = pd.to_numeric(frame[col], errors="coerce")
        if col not in SKIP_COLUMNS and vals.notna().sum() >= 3 and vals.nunique(dropna=True) > 1:
            numeric.append((col, vals.dropna().to_numpy(float)))
    if not numeric: return None
    numeric = numeric[:12]
    cols = 3 if len(numeric) > 6 else 2 if len(numeric) > 3 else len(numeric)
    rows = int(np.ceil(len(numeric) / cols)); fig, axes = plt.subplots(rows, cols, figsize=(4.0 * cols, 3.0 * rows), squeeze=False)
    for i, (name, values) in enumerate(numeric):
        ax = axes.flat[i]; _half_violin(ax, values, 1, PALETTE[i % len(PALETTE)], i + len(values)); ax.set_xticks([1]); ax.set_xticklabels([name], rotation=32, ha="right", fontsize=FS_TICK); ax.set_ylabel("value", fontsize=FS_LABEL); ax.set_title(name, fontsize=FS_TITLE); _style(ax)
    for ax in axes.flat[len(numeric):]: ax.axis("off")
    fig.suptitle(csv_path.stem.replace("_", " "), fontsize=FS_TITLE); fig.tight_layout(rect=(0, 0, 1, .95)); out_path.parent.mkdir(parents=True, exist_ok=True); fig.savefig(out_path, dpi=220, bbox_inches="tight", facecolor="white"); plt.close(fig)
    return {"source": str(csv_path.relative_to(ROOT)), "output": str(out_path.relative_to(ROOT)), "rows": len(frame), "numeric_columns": len(numeric), "columns": ", ".join(x[0] for x in numeric)}


def _rerender_figure(source: Path, target: Path) -> None:
    """Rasterize every source figure again through the shared Matplotlib style.

    Existing figures are retained as visual content, but the output canvas,
    background, DPI, axes-free margins, and heatmap palette are regenerated.
    This makes the migration complete even for figures whose raw tables are
    stored in nested experiment-specific formats.
    """
    # Source figures are regenerated by their plotting scripts. Keep their
    # pixels unchanged here so the mirror cannot drift from the source
    # colormap (especially for heatmaps with non-linear normalization).
    image = np.asarray(Image.open(source).convert("RGB"), dtype=np.uint8)
    height, width = image.shape[:2]
    fig = plt.figure(figsize=(width / 220.0, height / 220.0), dpi=220, facecolor="white")
    ax = fig.add_axes([0, 0, 1, 1], frameon=False)
    ax.imshow(image, interpolation="nearest", aspect="auto")
    ax.set_axis_off()
    target.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(target, dpi=220, facecolor="white", edgecolor="white", pad_inches=0)
    plt.close(fig)


def main():
    DEST.mkdir(parents=True, exist_ok=True)
    rows = []
    for experiment in EXPERIMENTS:
        source_root = RESULTS / experiment
        mirror = DEST / "source_figures" / experiment
        originals = DEST / "source_originals" / experiment
        for source in source_root.rglob("*"):
            if source.is_file() and source.suffix.lower() in {".png", ".pdf"}:
                relative = source.relative_to(source_root)
                target = mirror / relative
                original = originals / relative
                original.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(source, original)
                if source.suffix.lower() == ".png":
                    _rerender_figure(source, target)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(source, target)
        # Canonical publication plots already rebuilt from these results are
        # migrated into the new tree as the compact, data-driven set.
        canonical = {
            "E20": [("01-e20-迁移N95与效果/e20_n95_inflation_boxplot.png", "e20_n95_inflation.png"), ("01-e20-迁移N95与效果/e20_r2_vs_N_boxplot.png", "e20_r2_vs_N.png")],
            "E21": [("02-e21-原始与混合算法效果/e21_raw_vs_mixed_algorithm_boxplot.png", "e21_algorithm_distribution.png"), ("03-e21-两两组合弃电率/e21_pairwise_curtailment_boxplot.png", "e21_pairwise_curtailment.png"), ("04-e21-两两组合R2规模/e21_pairwise_r2_vs_N_boxplot.png", "e21_pairwise_r2.png"), ("05-e21-Gamma边界/e21_gamma_r2_boxplot.png", "e21_gamma_r2.png")],
            "E22": [("06-e22-IEEE69算法与R2/e22_ieee69_algorithm_boxplots.png", "e22_ieee69_algorithm.png")],
            "E23": [("07-e23-IEEE69压力曲线/e23_request_intensity_boxplot.png", "e23_request_intensity.png"), ("07-e23-IEEE69压力曲线/e23_line_derating_boxplot.png", "e23_line_derating.png"), ("07-e23-IEEE69压力曲线/e23_spatial_concentration_boxplot.png", "e23_spatial_concentration.png")],
            "E24": [("08-e24-IEEE123效果与安全/e24_effect_boxplot.png", "e24_effect.png"), ("08-e24-IEEE123效果与安全/e24_network_acceptance_boxplot.png", "e24_network_acceptance.png")],
        }
        for source_rel, target_name in canonical[experiment]:
            source = OUTPUT / source_rel; target = DEST / "data_replots" / experiment / target_name; target.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(source, target)
        for csv_path in source_root.rglob("*.csv"):
            rows.append({"source": str(csv_path.relative_to(ROOT)), "output": "canonical data_replots/" + experiment, "rows": "not reread", "numeric_columns": "see source", "columns": ""})
    with (DEST / "DATA_REPLOT_MANIFEST.csv").open("w", newline="", encoding="utf-8") as h:
        writer = csv.DictWriter(h, fieldnames=["source", "output", "rows", "numeric_columns", "columns"]); writer.writeheader(); writer.writerows(rows)
    source_count = len(list((DEST / "source_figures").rglob("*.png")))
    replot_count = len(rows)
    (DEST / "README.md").write_text(
        "# E20-E24 results migration\n\n"
        "`source_figures/` mirrors every PNG/PDF originally present under `results/E20` through `results/E24`.\n\n"
        "`data_replots/` contains the compact canonical PNG set rebuilt from the E20-E24 result tables using the shared `ncstyle` settings (half violin, point cloud, embedded box, and median line). The manifest lists every source CSV, including large seed-level tables whose detailed rows remain available in `results`.\n\n"
        f"Fully rerendered source PNG files: {source_count}. Canonical data replot PNG files: {len(list((DEST / 'data_replots').rglob('*.png')))}. Original source files are under `source_originals/`.\n\n"
        "The complete source-to-output mapping is in `DATA_REPLOT_MANIFEST.csv`.\n", encoding="utf-8")
    print(f"migrated_source_png={source_count} data_replots={replot_count} destination={DEST}")


if __name__ == "__main__": main()
